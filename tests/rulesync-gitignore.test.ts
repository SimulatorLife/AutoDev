import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import test from "node:test";

import { parseJsoncObject } from "@simulatorlife/autodev-data/files";

import { runRulesyncGitignore } from "../runtime/src/platform/runtime-files.ts";

const repositoryRoot = path.resolve(import.meta.dirname, "..");

/**
The generated-output exclusions belong to stock Rulesync.

`rulesync gitignore` derives the paths the configured targets own and, with
`"gitignoreDestination": "gitexclude"`, writes them to the repository's
exclude file. That keeps them out of the tracked `.gitignore`, which is what
lets Antigravity read the generated `.agents/skills/` tree: a tree listed in
`.gitignore` is a tree Antigravity refuses to load.
*/
function excludePath(): string {
  return execFileSync(
    "git",
    ["rev-parse", "--path-format=absolute", "--git-path", "info/exclude"],
    { cwd: repositoryRoot, encoding: "utf8" }
  ).trim();
}

function isIgnored(relativePath: string): boolean {
  try {
    execFileSync(
      "git",
      ["check-ignore", "--no-index", "--quiet", relativePath],
      { cwd: repositoryRoot, stdio: "pipe" }
    );
    return true;
  } catch {
    return false;
  }
}

test("stock Rulesync owns the generated-output exclusions in the exclude file", () => {
  runRulesyncGitignore(repositoryRoot);
  const exclude = readFileSync(excludePath(), "utf8");
  assert.match(exclude, /# Generated by Rulesync/);
  assert.match(exclude, /# End of Rulesync/);
  // The Antigravity hazard: this tree has to be excluded from Git's view
  // without being listed in `.gitignore`.
  assert.match(exclude, /^\*\*\/\.agents\/skills\/$/m);
  assert.match(exclude, /^\*\*\/\.agents\/hooks\.json$/m);
  assert.match(exclude, /^\*\*\/\.github\/hooks\/copilot-hooks\.json$/m);
});

test("the tracked .gitignore keeps the Rulesync block out of the repository", () => {
  const tracked = readFileSync(path.join(repositoryRoot, ".gitignore"), "utf8");
  assert.doesNotMatch(tracked, /# Generated by Rulesync/);
  assert.doesNotMatch(tracked, /^\*\*\/\.agents\/skills\/$/m);
});

test("the tracked rule files stay visible to tools that apply Git's ignore rules", () => {
  // The exclude file lists `**/AGENTS.md` and `**/CLAUDE.md`, because Rulesync
  // generates rule projections. These two are tracked repository content, so
  // the tracked `.gitignore` re-includes them: Git reads `.gitignore` before
  // the exclude file, and an ignore rule for a tracked file still hides it
  // from every tool that walks the tree with Git's ignore rules applied.
  const tracked = readFileSync(path.join(repositoryRoot, ".gitignore"), "utf8");
  assert.match(tracked, /^!\/AGENTS\.md$/m);
  assert.match(tracked, /^!\/CLAUDE\.md$/m);
  assert.equal(isIgnored("AGENTS.md"), false);
  assert.equal(isIgnored("CLAUDE.md"), false);
});

test("the exclusion run is idempotent", () => {
  runRulesyncGitignore(repositoryRoot);
  const before = readFileSync(excludePath(), "utf8");
  runRulesyncGitignore(repositoryRoot);
  assert.equal(readFileSync(excludePath(), "utf8"), before);
});

test("the repository configuration routes the exclusions to the exclude file", () => {
  const config = parseJsoncObject(
    readFileSync(path.join(repositoryRoot, "rulesync.jsonc"), "utf8"),
    "rulesync.jsonc"
  ) as Record<string, unknown>;
  assert.equal(config.gitignoreDestination, "gitexclude");
  assert.ok(
    existsSync(path.join(repositoryRoot, "node_modules", ".bin", "rulesync"))
  );
});
