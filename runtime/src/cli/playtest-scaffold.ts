/**
 * `autodev playtest init --scaffold` — generated bodies for a game that cannot
 * onboard declaratively.
 *
 * The declarative tier asks a game for declarations only: six plain functions
 * on the object its entry factory returns. That is not always achievable — an
 * engine whose reset lives behind a wrapper, or whose legal actions come from
 * a generator, may need AutoDev to write the body that bridges them.
 *
 * The scaffold writes those bodies as throwing stubs, not plausible ones. A
 * generated method that returned a well-shaped empty observation would pass
 * `conformance`, produce episodes, and hand the analyst measurements no game
 * ever made — which is the exact failure the declarative tier exists to
 * prevent. Every stub throws with the game's own file and the binding name, so
 * the first run names what to write.
 *
 * The binding this writes declares tier `generated-scaffold`, so a reviewer can
 * see that AutoDev generated the bodies and the game filled them in, rather
 * than that the game declared them.
 */

/** Bodies AutoDev can bridge for a game, and what each one must return. */
const SCAFFOLD_BODIES: readonly {
  readonly name: string;
  readonly contract: string;
}[] = [
  {
    name: "reset",
    contract:
      "// Return { episodeId, revision: 0, rngProvenance: { algorithm, version,\n  // initialStateHash, reproducible } } for the scenario and seed AutoDev sends."
  },
  {
    name: "observe",
    contract:
      "// Return { episodeId, revision, observation, turnContext, frame }.\n  // `observation` is what a player can see; see playtest.observation.json."
  },
  {
    name: "legalActions",
    contract:
      "// Return { episodeId, revision, actions: [{ actionId, description,\n  // features }] } — the actions legal right now, not every action."
  },
  {
    name: "step",
    contract:
      "// Return { episodeId, revision: expectedRevision + 1, acceptedActionId,\n  // eventIds, terminal }. revision must advance or the Runtime rejects it."
  },
  {
    name: "outcome",
    contract:
      "// Return { episodeId, revision, state, outcome, metrics, evaluations,\n  // missingReasons }. See playtest.rubric.json for the metrics you report."
  }
];

/**
 * The adapter module AutoDev generates.
 *
 * Every body throws. `conformance` runs this and fails at the first method it
 * reaches, naming the file to edit — which is the intended first experience of
 * a generated scaffold, and the reason this is not a set of empty returns.
 */
export function scaffoldAdapterModule(input: {
  readonly factory: string;
  readonly fileName: string;
}): string {
  const bodies = SCAFFOLD_BODIES.map(
    ({ name, contract }) => `  ${name}(params) {
    ${contract}
    throw new Error(
      "AutoDev generated this ${name} body for ${input.fileName}; implement it against your engine."
    );
  },`
  ).join("\n\n");
  return `// Generated by "autodev playtest init --scaffold". Replace every body below.
//
// Each one throws until you write it. That is deliberate: a stub that returned
// a well-shaped empty result would pass "autodev playtest conformance" and
// produce episodes that measure nothing the game did.

export function ${input.factory}() {
  return {
${bodies}

    // Optional methods AutoDev will not answer for you. Bind one in
    // playtest.binding.json and it becomes available; leave it out and the
    // Runtime is told the capability is absent rather than being misled.
    // fork(params) {},
    // replay(params) {},
    // captureEvents(params) {},
    // captureFrame(params) {},
    // invariants(params) {},
    // snapshot(params) {}
  };
}
`;
}

/** How many bodies a generated module contains; reported by `--scaffold`. */
export const PLAYTESTS_SCAFFOLD_BODY_COUNT = SCAFFOLD_BODIES.length;

/** The binding that goes with a generated module. */
export function scaffoldBinding(input: {
  readonly factory: string;
  readonly fileName: string;
}): string {
  const bindings = Object.fromEntries(
    SCAFFOLD_BODIES.map(({ name }) => [name, { export: name }])
  );
  return `${JSON.stringify(
    {
      schema: "autodev-playtest-adapter-binding-v1",
      schemaVersion: 1,
      // AutoDev wrote these bodies; the game fills them in. Saying so keeps the
      // tier a fact about how the code came to exist.
      tier: "generated-scaffold",
      entry: input.fileName,
      factory: input.factory,
      // Placeholders the game replaces with its own shapes. AutoDev hashes
      // these rather than trusting a digest written beside them.
      schemas: {
        observation: { type: "object", properties: {} },
        action: { type: "object", properties: {} },
        event: { type: "object", properties: {} }
      },
      bindings
    },
    null,
    2
  )}\n`;
}
